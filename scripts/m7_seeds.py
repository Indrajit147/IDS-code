"""Summarize repeats with other seeds: reports/<milestone>/<pool>/summary.json plus <pool>/seed*/summary.json -> SEEDS.md.

Usage: python scripts/m7_seeds.py [--pool dev|full] [--milestone m7|m8]
"""
from __future__ import annotations

import argparse
import json

import numpy as np

from ids.utils.config import REPO_ROOT

BASE = {"m7": "local_rehearsal", "m8": "e3", "m9": "e3"}   # what each milestone compares against


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pool", default="dev")
    ap.add_argument("--milestone", default="m7", choices=sorted(BASE))
    args = ap.parse_args()
    pool, ms = args.pool, args.milestone
    base = BASE[ms]
    rep = REPO_ROOT / "reports" / ms / pool
    files = [rep / "summary.json", *sorted(rep.glob("seed*/summary.json"))]
    runs = []
    for f in files:
        s = json.loads(f.read_text(encoding="utf-8"))
        runs.append({x["method"]: x for x in [*s["summaries"], *s["references"]] if x["method"] not in ("E1", "static")})

    def stat(m, key):
        v = [r[m][key] for r in runs]
        if None in v:   # a model that is never updated has no forgetting
            return "n/a"
        return f"{np.mean(v):.4f} ± {np.std(v, ddof=1):.4f}"

    t = (f"| method | window avg | final (t5) | class forgetting | window avg minus {base}, per seed | final minus {base}, per seed |\n"
         "|---|---:|---:|---:|---:|---:|\n")
    # a seed without M6's report has no naive_incremental row, so compare only what every run has
    methods = [m for m in runs[0] if all(m in r for r in runs)]
    for m in methods:
        da = ", ".join(f"{r[m]['window_avg_macro_f1'] - r[base]['window_avg_macro_f1']:+.4f}" for r in runs)
        df = ", ".join(f"{r[m]['final_macro_f1'] - r[base]['final_macro_f1']:+.4f}" for r in runs)
        t += f"| {m} | {stat(m, 'window_avg_macro_f1')} | {stat(m, 'final_macro_f1')} | {stat(m, 'mean_forgetting_by_class')} | {da} | {df} |\n"
    md = f"""# {ms.upper()} across seeds (`{pool}` pool)

Generated by `scripts/m7_seeds.py` from {len(runs)} runs. Mean ± sample standard deviation. The seed changes model fitting, validation rows, buffer sampling and the calibrator's sample; the partition stays fixed.

{t}"""
    (rep / "SEEDS.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
