"""M15: the paper's tables and figures, from committed reports only (no training), mapped to the IEEE IoT-J outline.

Writes paper/tables/*.tex (booktabs; each starts with a comment naming its source files) and paper/figures/*.png,
and paper/ARTIFACTS.md, which lists every table and figure under the outline section it serves.
Run: python scripts/m15_paper.py   (run scripts/m14_report.py first if the M14 tables changed)
"""
from __future__ import annotations

import json
import shutil

import pandas as pd

from ids.utils.config import REPO_ROOT

REP, PAPER = REPO_ROOT / "reports", REPO_ROOT / "paper"
M14 = REP / "m14" / "full"
HEADLINE_ROWS = {  # headline.csv name -> paper label, in the order of the table
    "E1 centralized": "E1 centralized", "static": "Static (t0 only)", "naive incremental": "Naïve incremental",
    "local + rehearsal": "Local + rehearsal", "E2 FedAvg": "E2 FedAvg", "E2 FedProx": "E2 FedProx", "FedMD": "FedMD",
    "E3": "E3 DA-FedDistill", "E4 (e4_added)": "E4 E3 + drift triggers", "E7 federated GBDT": "E7 federated GBDT"}


def tex(name: str, sources: list[str], caption: str, header: list[str], rows: list[list[str]], align: str) -> str:
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    out = (f"% generated by scripts/m15_paper.py from {', '.join(sources)}\n"
           f"\\begin{{table}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{tab:{name}}}\n"
           f"\\begin{{tabular}}{{{align}}}\n\\toprule\n{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n")
    (PAPER / "tables" / f"{name}.tex").write_text(out, encoding="utf-8", newline="\n")
    return name


def esc(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def f4(x) -> str:
    return f"{x:.4f}"


def signed(x, tiny: bool = False) -> str:
    return (f"{x:+.2e}" if tiny else f"{x:+.4f}").replace("-", "$-$")


def diff_cells(d, lo, hi) -> list[str]:
    """Difference and interval in one notation: scientific only when all three are tiny (H2a's variance), else 4 decimals."""
    tiny = 0 < max(abs(d), abs(lo), abs(hi)) < 5e-4
    return [signed(d, tiny), f"[{signed(lo, tiny)}, {signed(hi, tiny)}]"]


def pval(p: float, draws: int = 10_000) -> str:
    return f"$<10^{{-4}}$" if p == 0 and draws == 10_000 else f"{p:.3g}"


def headline() -> str:
    h = pd.read_csv(M14 / "headline.csv").set_index("method")
    rows = [[esc(lab), f"{h.at[m, 'window_avg']:.4f} $\\pm$ {h.at[m, 'window_avg_std']:.4f}",
             f"[{h.at[m, 'lo']:.3f}, {h.at[m, 'hi']:.3f}]", f"{h.at[m, 't5']:.4f} $\\pm$ {h.at[m, 't5_std']:.4f}"]
            for m, lab in HEADLINE_ROWS.items()]
    return tex("headline", ["reports/m14/full/headline.csv"],
               "Window-averaged and final (t5) macro-F1 on CSV rows, mean $\\pm$ SD over seeds 42--44; 95\\% client-bootstrap interval of the window average.",
               ["Method", "Window avg.", "95\\% interval", "Final (t5)"], rows, "lccc")


def hypotheses() -> str:
    h = pd.read_csv(M14 / "hypotheses.csv")
    rows = [[r.id, esc(r.test), *diff_cells(r.diff, r.lo, r.hi), pval(r.p_holm), "yes" if r.result == "yes" else "no"]
            for r in h.itertuples()]
    return tex("hypotheses", ["reports/m14/full/hypotheses.csv"],
               "H1--H3: paired client bootstrap (10{,}000 draws, seeds averaged within each draw), Holm-corrected over five tests. "
               "Supported if the interval excludes 0, $p_\\mathrm{Holm} < 0.05$ and, for macro-F1, $|\\Delta| \\geq 0.005$.",
               ["", "Test", "$\\Delta$", "95\\% interval", "$p_\\mathrm{Holm}$", "Supported"], rows, "llcccc")


def ablation() -> str:
    a = pd.read_csv(M14 / "ablation.csv")
    rows = [[esc(r.ablation), esc(r.against), *diff_cells(r.diff, r.lo, r.hi), pval(r.p, r.draws), r.result]
            for r in a.itertuples()]
    return tex("ablation", ["reports/m14/full/ablation.csv"],
               "Ablations: change in window-averaged macro-F1 (LLM rows: macro-F1 on the sampled rows), paired client bootstrap, seeds 42--44. "
               "``Meets rule'': interval excludes 0 and $|\\Delta| \\geq 0.005$.",
               ["Ablation", "Against", "$\\Delta$", "95\\% interval", "$p$", "Meets rule"], rows, "llcccc")


def llm() -> str:
    d = pd.read_csv(M14 / "llm.csv")
    rows = [[esc(r.setting), esc(r.rows.replace("_", "-")), esc(r.method), f"{r.macro_f1:.4f} $\\pm$ {r.macro_f1_std:.4f}",
             f"{r.fp_rate:.4f} $\\pm$ {r.fp_rate_std:.4f}"] for r in d.sort_values(["setting", "rows", "method"]).itertuples()]
    return tex("llm", ["reports/m14/full/llm.csv"],
               "LLM verification (Gemma 2 2B) on sampled test rows, seeds 42--44: boundary = the model trained through $t-1$ scored on window $t$ (high drift). "
               "False-positive rate = benign rows given an attack label.",
               ["Setting", "Rows", "Method", "Macro-F1", "FP rate"], rows, "lllcc")


def sensitivity() -> str:
    s = pd.read_csv(M14 / "sensitivity.csv")
    rows = [[esc(r.variant), str(r.clients), f4(r.E1), f4(r.local), f4(r.E3), f4(r.E4),
             f"{signed(r.E3_minus_local)} [{signed(r.E3_minus_local_lo)}, {signed(r.E3_minus_local_hi)}]"] for r in s.itertuples()]
    return tex("sensitivity", ["reports/m14/full/sensitivity.csv"],
               "Sensitivity, seed 42, one run per variant: window-averaged macro-F1 on CSV rows; E3 $-$ local with a 95\\% client interval.",
               ["Variant", "Clients", "E1", "Local", "E3", "E4", "E3 $-$ local"], rows, "lcccccc")


def explanations() -> str:
    h = pd.read_csv(M14 / "h4.csv")
    v = h[h.source.str.startswith("M11")]
    p = h[h.source.str.startswith("M12")]
    mean = lambda d, c: f"{d[c].mean():.3f}"
    rows = [["Reasons naming a top-5 SHAP feature", mean(v, "names_top5_feature")],
            ["Reasons grounded (feature and direction match SHAP)", mean(v, "grounded_strict")],
            ["Replies with every reason grounded", mean(v, "replies_all_grounded")],
            ["Verifier replies schema-valid, first try", mean(v, "valid_first_try")],
            ["Verifier replies schema-valid, after retries", mean(v, "valid_after_retries")],
            ["Policy replies schema-valid, first try", mean(p, "valid_first_try")]]
    return tex("explanations", ["reports/m14/full/h4.csv"],
               f"H4 (a) groundedness and (b) schema validity: mean over M11 seeds {', '.join(map(str, v.seed))} (verifier) and M12 seeds {', '.join(map(str, p.seed))} (policy agent).",
               ["Measure", "Share"], [[esc(a), b] for a, b in rows], "lc")


def efficiency() -> str:
    m4 = json.loads((REP / "m4" / "full" / "summary.json").read_text(encoding="utf-8"))
    lat, cost = m4["latency"]["t5"]["ensemble"], m4["cost"]["t5"]
    com = pd.read_csv(REP / "m7" / "full" / "communication.csv").set_index("train_through").loc[5]
    m8 = pd.read_csv(REP / "m8" / "full" / "cost.csv").query("method == 'fedavg'")
    m13 = json.loads((REP / "m13" / "full" / "summary.json").read_text(encoding="utf-8"))["cost"][-1]
    m11 = json.loads((REP / "m11" / "full" / "summary.json").read_text(encoding="utf-8"))
    calls, bat = m11["llm_calls_per_1k_full_stream_e5"], m11["batch_seconds"]
    rows = [
        ["Edge", "Ensemble latency, one flow (p50 / p95)", f"{lat['single_ms_p50']:.2f} / {lat['single_ms_p95']:.2f} ms"],
        ["Edge", "Ensemble, batched", f"{lat['batch_us_per_row']:.1f} $\\mu$s per flow"],
        ["Edge", "Model size; trees (XGBoost + LightGBM)", f"{cost['size_mb']:.1f} MB; {cost['xgb_trees']} + {cost['lgb_trees']}"],
        ["FL", "E3/E4 uplink per client per round (float32 / 8-bit + zlib)", f"{com.e3_up_raw / 1e6:.2f} / {com.e3_up_q8_zlib / 1e6:.2f} MB"],
        ["FL", "E3/E4 downlink per client per round", f"{int(com.e3_down)} B"],
        ["FL", "E2 FedAvg per client per round, each way; rounds", f"{m8.model_bytes.iloc[0] / 1e3:.1f} kB; {int(m8.rounds_run.sum())}"],
        ["FL", "E7 uplink per client at t5 (upper bound)", f"{m13['upload_bytes_per_client'] / 1e9:.1f} GB ({m13['upload_bytes_per_client'] / com.e3_up_raw:,.0f}$\\times$ E3)"],
        ["Cloud", "Escalation payload", f"{m11['payload_bytes_mean']:.0f} B"],
        ["Cloud", "LLM calls per 1k flows: E5 boundary / own window; E6", f"{calls['boundary']:.1f} / {calls['own window']:.1f}; {m11['llm_calls_per_1k_e6']:.0f}"],
        ["Cloud", "LLM latency per batch of 16 (mean / p95, T4, 4-bit)", f"{bat['mean_ms'] / 1e3:.1f} / {bat['p95_ms'] / 1e3:.1f} s"],
    ]
    return tex("efficiency", ["reports/m4/full/summary.json", "reports/m7/full/communication.csv", "reports/m8/full/cost.csv",
                              "reports/m13/full/summary.json", "reports/m11/full/summary.json"],
               "System cost, full pool, seed 42: edge (t5 model, one CPU thread), federated communication, cloud verification.",
               ["Part", "Measure", "Value"], [[a, esc(b) if "$" not in b else b, c] for a, b, c in rows], "llr")


SECTIONS = {
    "Experimental setup": ["setup: `release/window_definition.json`, `release/client_partitions.json`, `reports/m2/full/PARTITION.md`"],
    "Results: detection and drift robustness": ["headline", "hypotheses", "fig:macro_f1_by_window"],
    "Results: ablations and sensitivity": ["ablation", "sensitivity"],
    "Results: efficiency": ["efficiency"],
    "Results: LLM verification and interpretability": ["llm", "explanations", "fig:frontier"],
    "Discussion: cost-accuracy frontier": ["fig:frontier", "reports/m14/full/TIER3.md"],
    "System and threat model": ["paper/threat_model.md"],
    "Reproducibility and artifacts": ["release/README.md", "notebooks/m15_notebook_a.ipynb", "notebooks/m15_notebook_b.ipynb", "scripts/m15_check.py"],
}


def main() -> None:
    (PAPER / "tables").mkdir(parents=True, exist_ok=True)
    (PAPER / "figures").mkdir(parents=True, exist_ok=True)
    made = [f() for f in (headline, hypotheses, ablation, sensitivity, efficiency, llm, explanations)]
    for fig in ("macro_f1_by_window.png", "frontier.png"):
        shutil.copyfile(M14 / fig, PAPER / "figures" / fig)
    lines = ["# Paper artifacts by outline section", "", "Generated by `scripts/m15_paper.py` from committed reports. Tables are in `tables/` (LaTeX, booktabs), figures in `figures/`.", ""]
    for sec, items in SECTIONS.items():
        refs = []
        for it in items:
            if it in made:
                refs.append(f"[table `{it}`](tables/{it}.tex)")
            elif it.startswith("fig:"):
                refs.append(f"[figure `{it[4:]}`](figures/{it[4:]}.png)")
            else:
                refs.append(it)
        lines.append(f"- **{sec}:** " + "; ".join(refs))
    (PAPER / "ARTIFACTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"paper -> {PAPER}: {len(made)} tables, 2 figures")


if __name__ == "__main__":
    main()
