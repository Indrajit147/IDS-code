"""Summarize M6 repeats with other seeds: reports/m6/<pool>/summary.json plus <pool>/seed*/summary.json -> SEEDS.md.

Usage: python scripts/m6_seeds.py [--pool dev|full]
"""
from __future__ import annotations

import argparse
import json

import numpy as np

from ids.utils.config import REPO_ROOT


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pool", default="dev")
    pool = ap.parse_args().pool
    rep = REPO_ROOT / "reports" / "m6" / pool
    files = [rep / "summary.json", *sorted(rep.glob("seed*/summary.json"))]
    runs = [{s["method"]: s for s in json.loads(f.read_text(encoding="utf-8"))["summaries"]} for f in files]
    base = [r["naive_incremental"]["mean_forgetting_by_class"] for r in runs]

    def stat(m, key):
        v = [r[m][key] for r in runs]
        return f"{np.mean(v):.4f} ± {np.std(v, ddof=1):.4f}"

    t = ("| method | window avg | avg excl. t0 | final (t5) | class forgetting | forgetting minus naive, per seed |\n"
         "|---|---:|---:|---:|---:|---:|\n")
    for m in runs[0]:
        d = ", ".join(f"{r[m]['mean_forgetting_by_class'] - b:+.4f}" for r, b in zip(runs, base))
        t += (f"| {m} | {stat(m, 'window_avg_macro_f1')} | {stat(m, 'window_avg_macro_f1_excl_t0')} | "
              f"{stat(m, 'final_macro_f1')} | {stat(m, 'mean_forgetting_by_class')} | {d} |\n")
    md = (f"# M6 across seeds (`{pool}` pool)\n\nGenerated by `scripts/m6_seeds.py` from {len(runs)} runs. Mean ± sample standard deviation. "
          "The seed changes model fitting, validation rows and buffer sampling; the partition stays fixed.\n\n" + t)
    (rep / "SEEDS.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
