"""M13: E7, horizontal federated XGBoost by histogram aggregation (relaxed privacy), incremental per window.

One global XGBoost. At t0 it fits up to first_trees rounds, and each later window adds up to new_trees rounds on that
window's rows of every client, with no rehearsal buffer and no feature selection (the proposal's E7 row). Every fit
is a real federated run: one worker process per client, holding only its rows (src/ids/fl/fedgbdt.py). See README, M13.

Usage: python scripts/m13_fedgbdt.py [--pool dev|full] [--env ...] [--set KEY=VALUE ...] [--tag ...]
"""
from __future__ import annotations

import argparse
import json
import time

import numpy as np
import pandas as pd
import xgboost as xgb

from ids.data.io import model_features
from ids.data.schema import CATEGORIES
from ids.eval.harness import Evaluator, client_clusters, load_test_sets, predict_global
from ids.eval.plots import fig_curves
from ids.fl.fedgbdt import federated_train, global_balanced_weights, histogram_upload_bytes
from ids.models.edge import val_split
from ids.partition.io import load_rows
from ids.utils import Run, load_config, set_global_seed
from ids.utils.config import REPO_ROOT
from ids.utils.jsonl import dumps
from ids.utils.run import memory_note

HEADLINE = "csv_only"    # D7
NAME = "e7"
# (report folder, method) of the references, all seed 42 on the same pool
REFS = {"E1 centralized (M3)": ("m4", "E1"), "Naive incremental, local (M6)": ("m6", "naive_incremental"),
        "E3 DA-FedDistill (M7)": ("m7", "e3"), "E4 (M9, e4_added)": ("m9", "e4_added")}


class GlobalModel:
    def __init__(self, raw: bytes, n_jobs: int):
        self.booster = xgb.Booster(model_file=bytearray(raw))
        self.booster.set_param({"nthread": n_jobs})

    def predict_components(self, X):
        return {"xgb": self.booster.predict(xgb.DMatrix(X))}


def xgb_params(cfg: dict, n_workers: int) -> dict:
    mc, ic = cfg["models"], cfg["incremental"]
    p = {k: v for k, v in mc["xgb"].items() if k != "n_estimators"}
    # IncrementalEdge's XGBoost settings (M6), so E7 differs from the per-client boosters only in being federated
    return {"objective": "multi:softprob", "num_class": len(CATEGORIES), "tree_method": "hist", "eval_metric": "mlogloss",
            "seed": cfg["seed"], "base_score": 0.5, "min_child_weight": 1e-3, **p, "max_delta_step": ic["max_delta_step"],
            "nthread": max(1, cfg["resources"]["n_jobs"] // n_workers) if cfg["resources"]["n_jobs"] > 0 else 1}


def references(pool: str) -> list[dict]:
    out = []
    for label, (m, method) in REFS.items():
        f = REPO_ROOT / "reports" / m / pool / "summary.json"
        if not f.exists():
            continue
        s = next((x for x in json.loads(f.read_text(encoding="utf-8"))["summaries"] if x["method"] == method and x["slice"] == HEADLINE), None)
        if s:
            out.append({**s, "label": label, "macro_f1_by_window": {int(k): v for k, v in s["macro_f1_by_window"].items()}})
    return out


def write_report(rep, x) -> None:
    def row(label, s):
        f = s["mean_forgetting_by_class"]
        return (f"| {label} | {s['window_avg_macro_f1']:.4f} | {s['window_avg_macro_f1_excl_t0']:.4f} | {s['final_macro_f1']:.4f} | "
                + ("n/a" if f is None else f"{f:.4f}") + " |")
    w = x["windows"]
    L = [f"# M13: E7, horizontal federated GBDT (`{x['pool']}` pool)", "",
         f"Run `{x['run']}`, seed {x['seed']}. Generated by `scripts/m13_fedgbdt.py`. Scores use CSV-only rows (D7); E7 is one global model.",
         "References are read from the earlier milestones' reports for the same pool (seed 42).", "",
         "| method | window avg | avg excl. t0 | final | class forgetting |", "|---|---:|---:|---:|---:|",
         row("**E7 federated GBDT**", x["e7"]), *[row(r["label"], r) for r in x["refs"]], "",
         "| method | " + " | ".join(w) + " |", "|---|" + "---:|" * len(w),
         "| **E7** | " + " | ".join(f"{x['e7']['macro_f1_by_window'][i]:.3f}" for i in range(len(w))) + " |",
         *[f"| {r['label']} | " + " | ".join(f"{r['macro_f1_by_window'][i]:.3f}" for i in range(len(w))) + " |" for r in x["refs"]], "",
         "![curves](macro_f1_by_window.png)", "", "## Cost", "",
         "Uplink: an upper bound per client, one gradient and one Hessian histogram (8-byte values, all bins) per new tree node, "
         "without XGBoost's subtraction trick, which halves it; the quantile sketch isn't counted. E3's is its raw float32 soft labels on D_pub (M7).", "",
         "| window | clients | rounds added | fit seconds | model MB | E7 uplink per client (MB) | E3 uplink per client (MB) |", "|---|---:|---:|---:|---:|---:|---:|"]
    for c in x["cost"]:
        e3 = c.get("e3_up_raw")
        L.append(f"| t{c['train_through']} | {c['clients']} | {c['rounds_added']} | {c['fit_seconds']:.0f} | {c['model_bytes'] / 1e6:.2f} | "
                 f"{c['upload_bytes_per_client'] / 1e6:.1f} | " + ("n/a" if e3 is None else f"{e3 / 1e6:.2f}") + " |")
    L += ["", "Stores: `summary.json`, `results.csv`, `per_class.csv`, `confusions.csv`, `cost.csv`."]
    (rep / "FEDGBDT.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", default=None)
    ap.add_argument("--pool", default=None, help="dev | full (default from resources.use_dev_sample)")
    ap.add_argument("--set", nargs="*", default=[], metavar="KEY=VALUE")
    ap.add_argument("--tag", default=None)
    args = ap.parse_args()
    cfg = load_config(env=args.env, overrides=args.set)
    set_global_seed(cfg["seed"])
    pool = args.pool or ("dev" if cfg["resources"]["use_dev_sample"] else "full")
    tl, windows, feats = cfg["timeline"]["headline"], cfg["timeline"]["windows"], model_features(cfg)
    target, mc, ic = cfg["labels"]["headline_target"], cfg["models"], cfg["incremental"]
    seed, K = cfg["seed"], len(CATEGORIES)
    rep = REPO_ROOT / "reports" / "m13" / pool / (args.tag or "")
    rep.mkdir(parents=True, exist_ok=True)

    with Run(cfg, f"m13_fedgbdt_{pool}") as run:
        log = run.logger
        ev = Evaluator(load_test_sets(cfg, pool, tl, target, feats), CATEGORIES, client_clusters(cfg, pool, tl, cfg["eval"]["n_client_clusters"]))
        e3_comm = REPO_ROOT / "reports" / "m7" / pool / "communication.csv"
        e3_up = pd.read_csv(e3_comm).set_index("train_through")["e3_up_raw"].to_dict() if e3_comm.exists() else {}
        model, cost = None, []
        for t in range(len(windows)):
            d = load_rows(cfg, pool, tl, windows=[t], split="train", features=feats)
            X, y, cl = d[feats].to_numpy(np.float32), d[target].to_numpy().astype(np.int64), d["client"].to_numpy()
            del d
            ids = [int(c) for c in np.unique(cl)]
            splits = []
            for c in ids:
                Xc, yc = X[cl == c], y[cl == c]
                vm = val_split(yc, mc["val_frac"], seed, ("m13", c, t))
                splits.append((Xc[~vm], yc[~vm], Xc[vm], yc[vm]))
            del X, y, cl
            # each client sends its class counts; the server returns the global balanced weights (M3's, capped)
            w_tr = global_balanced_weights(sum(np.bincount(s[1], minlength=K) for s in splits), mc["weight_cap"])
            w_va = global_balanced_weights(sum(np.bincount(s[3], minlength=K) for s in splits), mc["weight_cap"])
            parts = [(a, b, w_tr[b], av, bv, w_va[bv]) for a, b, av, bv in splits]
            del splits
            before = 0 if model is None else xgb.Booster(model_file=bytearray(model)).num_boosted_rounds()
            tic = time.perf_counter()
            model = federated_train(parts, xgb_params(cfg, len(parts)), ic["first_trees"] if model is None else ic["new_trees"],
                                    prev=model, early_stopping=mc["early_stopping"])
            secs = time.perf_counter() - tic
            del parts
            g = GlobalModel(model, cfg["resources"]["n_jobs"])
            rounds = g.booster.num_boosted_rounds()
            cost.append({"train_through": t, "clients": len(ids), "rounds_added": rounds - before, "rounds_total": rounds, "fit_seconds": round(secs, 2),
                         "model_bytes": len(model), "upload_bytes_per_client": histogram_upload_bytes(g.booster, before * K, len(feats), mc["xgb"]["max_bin"]),
                         "e3_up_raw": e3_up.get(t)})
            ev.evaluate(NAME, t, predict_global(g))
            log.info("[e7] t%d: %d clients, %d rounds added, %.0fs; %s", t, len(ids), rounds - before, secs, memory_note())

        s = ev.summary(NAME, HEADLINE, eps=cfg["eval"]["recover_eps"])
        refs = references(pool)
        ev.long_table().round(6).to_csv(rep / "results.csv", index=False)
        ev.per_class_table().round(6).to_csv(rep / "per_class.csv", index=False)
        ev.confusion_table().to_csv(rep / "confusions.csv", index=False)
        pd.DataFrame(cost).to_csv(rep / "cost.csv", index=False)
        (rep / "summary.json").write_text(dumps({"pool": pool, "seed": seed, "summaries": [s], "summaries_all_rows": [ev.summary(NAME, "all", eps=cfg["eval"]["recover_eps"])],
                                                 "references": refs, "cost": cost}, indent=2), encoding="utf-8")
        fig_curves({"E7 federated GBDT": pd.Series(s["macro_f1_by_window"]), **{r["label"]: pd.Series(r["macro_f1_by_window"]) for r in refs if "M6" not in r["label"]}},   # the palette has 4 slots
                   windows, rep / "macro_f1_by_window.png", "Macro-F1 per window, CSV rows only")
        write_report(rep, {"pool": pool, "run": run.dir.name, "seed": seed, "windows": windows, "e7": s, "refs": refs, "cost": cost})
        log.info("report -> %s", rep)


if __name__ == "__main__":
    main()
