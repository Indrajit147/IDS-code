"""M11, second verifier on a subset (the proposal: Mistral 7B "for a smaller subset").

Reads seed 42's full-pool M11 run (evidence.parquet, centroids.json, verified.parquet with Gemma's replies), takes the rows
that run sent to the verifier in a seeded random order drawn without labels, and verifies them in chunks until a time
budget runs out. Results are rewritten after every chunk, so a timeout still leaves a scored prefix of that order.
Scores are paired on the rows done: edge, Gemma and this verifier on the same rows. See README, M11.

Usage: python scripts/m11_subset.py --env kaggle --set llm.backend=hf llm.model_id=<path> [--hours 9] [--name mistral]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from m11_verify import BENIGN, override_counts, payload   # noqa: E402

from ids.data.schema import CATEGORIES   # noqa: E402
from ids.eval.system import latency_summary   # noqa: E402
from ids.llm.verifier import d3_allows, grounded, make_backend, verify   # noqa: E402
from ids.utils import Run, load_config, rng, set_global_seed   # noqa: E402
from ids.utils.config import REPO_ROOT   # noqa: E402
from ids.utils.jsonl import JsonlWriter, dumps   # noqa: E402

CODE = {c: i for i, c in enumerate(CATEGORIES)}


def order(v: pd.DataFrame, seed: int) -> np.ndarray:
    """Positions of the rows Gemma's run sent, in a label-free seeded random order."""
    sent = np.flatnonzero(v.llm.to_numpy() >= 0)
    return sent[rng(seed, "m11_subset").permutation(len(sent))]


def score(v: pd.DataFrame, done: pd.DataFrame) -> dict:
    """Paired comparison on the rows done: E5 on escalated rows, E6 on always-on rows, benign rows for false positives."""
    d = v.loc[done.index].join(done, rsuffix="_new")
    out = {"rows_done": len(d), "valid_first_try": float(d.first_try_valid_new.mean()), "valid_after_retries": float(d.valid_new.mean()),
           "fallbacks": int((~d.valid_new).sum()), "grounded": float(d.grounded_new[d.valid_new].mean()) if d.valid_new.any() else None}
    for name, m in (("escalated", d.escalated), ("always_on", d.always_on)):
        s = d[m]
        y, edge = s.y.to_numpy(), s.pred.to_numpy()
        res = {"rows": len(s), "edge_accuracy": float((edge == y).mean()) if len(s) else None}
        for who, lab, d3, ok in (("gemma", s.llm, s.d3, s.valid), ("new", s.llm_new, s.d3_new, s.valid_new)):
            lab, d3, ok = lab.to_numpy(), d3.to_numpy(), ok.to_numpy()
            res[who] = {"accuracy": float((lab == y).mean()) if len(s) else None, "disagrees_with_edge": float((lab != edge).mean()) if len(s) else None,
                        "d3": override_counts(y, edge, np.where(d3, lab, edge)), "free": override_counts(y, edge, np.where(ok, lab, edge))}
        out[name] = res
    b = d[d.y == BENIGN]
    out["benign"] = {"rows": len(b), "edge_fp": int((b.pred != BENIGN).sum()), "gemma_free_fp": int((b.llm != BENIGN).sum()), "new_free_fp": int((b.llm_new != BENIGN).sum()),
                     "gemma_d3_fp": int((np.where(b.d3, b.llm, b.pred) != BENIGN).sum()), "new_d3_fp": int((np.where(b.d3_new, b.llm_new, b.pred) != BENIGN).sum())}
    out["crosstab_edge_x_new"] = pd.crosstab(d.pred.map(dict(enumerate(CATEGORIES))), d.llm_new.map(dict(enumerate(CATEGORIES)))).to_dict()
    return out


def report(rep: Path, s: dict) -> None:
    L = [f"# M11: second verifier on a subset, `{s['pool']}` pool, seed {s['seed']}", "",
         f"Generated by `scripts/m11_subset.py`. Verifier: **{s['model']}**, against the first verifier, {s['first']}, on the same rows (seed 42's M11 run).",
         f"Rows: {s['rows_done']:,} of the {s['rows_sent']:,} that run sent, taken in a seeded random order drawn without labels; stopped by {s['stopped_by']}.", "",
         f"**Valid replies:** {s['valid_first_try']:.4f} on the first try, {s['valid_after_retries']:.4f} after retries ({s['fallbacks']} fallbacks). **Grounded:** {s['grounded'] or 0:.3f}. "
         f"**Batch latency:** mean {s['batch_seconds']['mean_ms']:.0f} ms, P95 {s['batch_seconds']['p95_ms']:.0f} ms; {s['rows_per_second']:.2f} rows per second.", "",
         "| rows | n | edge accuracy | verifier | accuracy | disagrees with edge | D3: changed / fixed / broke | label whenever valid: changed / fixed / broke |",
         "|---|---:|---:|---|---:|---:|---|---|"]
    for name in ("escalated", "always_on"):
        r = s[name]
        for who in ("gemma", "new"):
            g = r[who]
            L.append(f"| {name} | {r['rows']} | {r['edge_accuracy'] or 0:.3f} | {s['first'] if who == 'gemma' else s['name']} | {g['accuracy'] or 0:.3f} | {g['disagrees_with_edge'] or 0:.3f} | "
                     f"{g['d3']['overrides']} / {g['d3']['fixed']} / {g['d3']['broke']} | {g['free']['overrides']} / {g['free']['fixed']} / {g['free']['broke']} |")
    b = s["benign"]
    L += ["", f"**Benign rows:** {b['rows']}. Called an attack by the edge: {b['edge_fp']}; under D3, {s['first']} {b['gemma_d3_fp']} and {s['name']} {b['new_d3_fp']}; "
          f"with the label whenever valid, {s['first']} {b['gemma_free_fp']} and {s['name']} {b['new_free_fp']}.", "",
          "`escalated`: E5's rows; `always_on`: E6's rows (a row can be both). Paired on the same rows; not comparable to the macro-F1 of the full sample.", "",
          "Stores: `subset.parquet` (one row per verified row), `batches.csv`, `summary.json`, `llm_log.jsonl` (every prompt and reply)."]
    (rep / "VERIFY.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", default=None)
    ap.add_argument("--set", nargs="*", default=[], metavar="KEY=VALUE")
    ap.add_argument("--hours", type=float, default=9.0, help="stop starting new chunks after this long")
    ap.add_argument("--chunk", type=int, default=160)
    ap.add_argument("--name", default="mistral")
    ap.add_argument("--pool", default="full")
    args = ap.parse_args()
    cfg = load_config(env=args.env, overrides=args.set)
    set_global_seed(cfg["seed"])
    lc, src = cfg["llm"], REPO_ROOT / "reports" / "m11" / args.pool
    rep = src / args.name
    rep.mkdir(parents=True, exist_ok=True)
    ev = pd.read_parquet(src / "evidence.parquet")
    v = pd.read_parquet(src / "verified.parquet")
    assert len(v) == len(ev) and (v.row.to_numpy() == ev.row.to_numpy()).all(), "evidence and verified rows differ"
    assert json.loads((src / "summary.json").read_text(encoding="utf-8"))["seed"] == 42, "expects seed 42's run"
    first = Path(json.loads((src / "summary.json").read_text(encoding="utf-8"))["model"]).parts
    first = max([x for x in first if "gemma" in x.lower()] or [first[-1]], key=len)   # the Kaggle path's variation name, e.g. gemma-2-2b-it
    cen = json.loads((src / "centroids.json").read_text(encoding="utf-8"))
    pos = order(v, cfg["seed"])
    with Run(cfg, f"m11_subset_{args.name}") as run:
        log = run.logger
        backend = make_backend(lc)
        start, recs, batches, stopped = time.time(), [], [], "the end of the rows"
        writer = JsonlWriter(rep / "llm_log.jsonl")
        for s0 in range(0, len(pos), args.chunk):
            if time.time() - start > args.hours * 3600:
                stopped = f"the {args.hours:g}-hour budget"
                break
            items = [{"key": int(i), "payload": payload(ev.iloc[i], cen, cfg["explain"]["top_k"])} for i in pos[s0:s0 + args.chunk]]
            r, b = verify(items, backend, CATEGORIES, cen["features"], lc["batch_size"], lc["max_retries"], writer)
            for rec, it in zip(r, items):
                x = v.iloc[rec["key"]]
                rec["payload"] = it["payload"]
                rec["d3"] = rec["valid"] and d3_allows(rec["reply"], bool(x.xgb_pred != x.lgb_pred), bool(x.hold or x.score > 0))
            recs += r
            batches += b
            done = pd.DataFrame({"llm": [CODE[q["reply"]["final_label"]] for q in recs], "valid": [q["valid"] for q in recs],
                                 "first_try_valid": [q["first_try_valid"] for q in recs], "attempts": [q["attempts"] for q in recs], "d3": [q["d3"] for q in recs],
                                 "grounded": [q["valid"] and grounded(q["reply"], q["payload"]) for q in recs]}, index=[q["key"] for q in recs])
            bt = pd.DataFrame(batches)
            summary = {"pool": args.pool, "seed": cfg["seed"], "name": args.name, "model": lc["model_id"], "first": first, "rows_sent": len(pos), "stopped_by": stopped,
                       "batch_seconds": latency_summary(1000 * bt.seconds.to_numpy()), "rows_per_second": float(bt.rows.sum() / bt.seconds.sum()), **score(v, done)}
            done.join(v[["row", "train_through", "eval_window", "client", "y", "pred", "escalated", "always_on"]]).to_parquet(rep / "subset.parquet")
            bt.round(4).to_csv(rep / "batches.csv", index=False)
            (rep / "summary.json").write_text(dumps(summary, indent=2), encoding="utf-8")
            report(rep, summary)
            log.info("%d of %d rows done, %.0f min; valid %.3f", len(recs), len(pos), (time.time() - start) / 60, summary["valid_after_retries"])
        summary["stopped_by"] = stopped
        (rep / "summary.json").write_text(dumps(summary, indent=2), encoding="utf-8")
        report(rep, summary)
        log.info("report -> %s (stopped by %s)", rep, stopped)


if __name__ == "__main__":
    main()
